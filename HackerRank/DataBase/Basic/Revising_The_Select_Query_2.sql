-- Descrption -> We Have to select the NAME from the CITY table where the COUNTRYCODE is USA and the POPULATION is greater than 120000.

-- Query ->
SELECT NAME From CITY
WHERE COUNTRYCODE = 'USA' AND POPULATION > 120000;